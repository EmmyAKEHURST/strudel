// -------------------- LES CONSTANTES --------------------

// Voici le gros vvrrrrrrrmmmmm derrière
const back = note("<c2 g#1 f1 g#1>/2").sound("supersaw")
  .seg(16)
  .lpf(200)
  .gain(1)
  .distort("2:.5")
  .room(1)
  .cutoff(slider(300,300,3000)) //a augmenter lors du drop "wow"
  .postgain(slider(1,0.1,1))
  ._pianoroll()

// vais-je mourir ?
const bipbip = stack(
  note("<c4!4 f3!2 g#3!2> -!7")
  .delay(.5)
  .room(1)
  .postgain(1),
  
  note("- - - c6, - - - c5").sound("wt_digital_basique")
  .room(1)
  .delay(.2)
  .sometimes(ply("2"))
  .postgain(.4)
)

// ça fait boom
const boom = sound("bd!4").bank("rolandtr909")
  .gain(.7)
  .room(.2)
  ._pianoroll()

// hithat qui part quasi jamais en couille mais quand même
const hithat = sound("compurhythm1000_hh!8")
  .decay(.8)
  .gain(.15)
  .lpf(8000)
  .almostNever(ply("2 | 4"))
  ._pianoroll()


// poudre de perlinpinping
const lesnotes = note("<c2 g#1 f1 g1>/4").sound("wt_digital_basique")
  .trans(36)
  .struct("x - x - - x - x").fast(2)
  .room(1)
  .sometimes(trans(12))
  .delay(.5)
  .postgain(.55)
  ._pianoroll()

// -------------------- ASSEMBLAGE --------------------

const un = back
const unbip = stack(back, bipbip)
const deux = stack(unbip, boom)
const trois = stack(deux, hithat)
const wow = stack(trois, lesnotes)

